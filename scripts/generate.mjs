// WalkBCN content generator.
//
// 1. Text:  asks Claude to retell each stop's story from the angle of every
//           interest that stop is tagged with (architecture, food, ...).
// 2. Audio: turns every story (the base one + each variant) into an audio file.
//
// Everything is generated ahead of time and saved in content/ and audio/, so the
// website never calls an AI service while people use it.
//
// Usage:
//   node scripts/generate.mjs              text + audio (only what's missing)
//   node scripts/generate.mjs --text       only stories
//   node scripts/generate.mjs --audio      only audio
//   node scripts/generate.mjs --force      redo everything
//   node scripts/generate.mjs --only=casa-batllo
//   node scripts/generate.mjs --mock       fake stories, no API call (to test the pipeline)
//
// Env:
//   ANTHROPIC_API_KEY     needed for --text
//   ELEVENLABS_API_KEY    optional: natural voices. Without it, the free macOS voice is used.
//   ELEVENLABS_VOICE_ID   optional: ElevenLabs voice (default: "George")
//   SAY_VOICE             optional: macOS voice (default: Daniel)

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { MODEL, writeVariants as writeStoryVariants } from "./story-writer.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT_JSON = path.join(ROOT, "content/stories.json");
const CONTENT_JS = path.join(ROOT, "content/stories.js");
const REVIEW_MD = path.join(ROOT, "content/review.md");
const AUDIO_DIR = path.join(ROOT, "audio");

const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);
const only = args.find((a) => a.startsWith("--only="))?.split("=")[1];
const doText = flag("text") || !flag("audio");
const doAudio = flag("audio") || !flag("text");
const FORCE = flag("force");
const MOCK = flag("mock");

// ---------- data ----------

function loadAllStops() {
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, "data/stops.js"), "utf8"), ctx);
  return ctx.window.WALKBCN_STOPS;
}

function loadContent() {
  return fs.existsSync(CONTENT_JSON) ? JSON.parse(fs.readFileSync(CONTENT_JSON, "utf8")) : {};
}

function saveContent(content) {
  fs.mkdirSync(path.dirname(CONTENT_JSON), { recursive: true });
  fs.writeFileSync(CONTENT_JSON, JSON.stringify(content, null, 2) + "\n");
  // A plain <script> works even when index.html is opened straight from disk.
  fs.writeFileSync(CONTENT_JS, `// Generated by scripts/generate.mjs — do not edit by hand.\nwindow.WALKBCN_STORIES = ${JSON.stringify(content, null, 2)};\n`);
}

const hash = (text) => crypto.createHash("sha1").update(text).digest("hex").slice(0, 10);

// ---------- 1. stories (Claude) ----------

async function writeVariants(stop) {
  if (MOCK) {
    return stop.tags.map((t) => ({ interest: t, story: `[${t} version] ${stop.story}`, facts_to_verify: [] }));
  }
  return writeStoryVariants(stop);
}

async function generateText(stops, content) {
  for (const stop of stops) {
    const entry = (content[stop.id] ??= { variants: {} });
    const todo = FORCE || stop.tags.some((t) => !entry.variants[t] || (entry.variants[t].mock && !MOCK));
    if (!todo) { console.log(`  ✓ ${stop.name} (already written)`); continue; }

    process.stdout.write(`  … ${stop.name} `);
    try {
      const variants = await writeVariants(stop);
      for (const v of variants) {
        entry.variants[v.interest] = {
          story: v.story.trim(),
          facts_to_verify: v.facts_to_verify ?? [],
          ...(MOCK && { mock: true }),
        };
      }
      saveContent(content); // save after every stop, so a crash never loses work
      console.log(`→ ${variants.length} versions`);
    } catch (err) {
      console.log(`✗ ${err.message} — keeping the base story for this stop`);
    }
  }
}

// ---------- 2. audio ----------

const ELEVEN_KEY = process.env.ELEVENLABS_API_KEY;
const AUDIO_EXT = ELEVEN_KEY ? "mp3" : "m4a";

async function speak(text, outFile) {
  if (ELEVEN_KEY) {
    const voice = process.env.ELEVENLABS_VOICE_ID || "JBFqnCBsd6RMkjVDRZzb";
    const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voice}?output_format=mp3_44100_128`, {
      method: "POST",
      headers: { "xi-api-key": ELEVEN_KEY, "Content-Type": "application/json", Accept: "audio/mpeg" },
      body: JSON.stringify({ text, model_id: "eleven_multilingual_v2" }),
    });
    if (!res.ok) throw new Error(`ElevenLabs ${res.status}: ${await res.text()}`);
    fs.writeFileSync(outFile, Buffer.from(await res.arrayBuffer()));
    return;
  }
  // Free fallback: the built-in macOS voice, converted to AAC (.m4a) so it plays in every browser.
  const tmpTxt = `${outFile}.txt`, tmpAiff = `${outFile}.aiff`;
  fs.writeFileSync(tmpTxt, text);
  try {
    execFileSync("say", ["-v", process.env.SAY_VOICE || "Daniel", "-r", "172", "-f", tmpTxt, "-o", tmpAiff]);
    execFileSync("afconvert", ["-f", "m4af", "-d", "aac", "-b", "64000", tmpAiff, outFile]);
  } finally {
    fs.rmSync(tmpTxt, { force: true });
    fs.rmSync(tmpAiff, { force: true });
  }
}

// Only re-records when the text changed (or with --force).
async function ensureAudio(holder, text, baseName, label) {
  const spoken = `${label}. ${text}`;
  const file = `${baseName}.${AUDIO_EXT}`;
  const abs = path.join(AUDIO_DIR, file);
  if (!FORCE && holder.audio === `audio/${file}` && holder.audioHash === hash(spoken) && fs.existsSync(abs)) return false;
  await speak(spoken, abs);
  holder.audio = `audio/${file}`;
  holder.audioHash = hash(spoken);
  return true;
}

async function generateAudio(stops, content) {
  fs.mkdirSync(AUDIO_DIR, { recursive: true });
  console.log(`  voice: ${ELEVEN_KEY ? "ElevenLabs" : `macOS "${process.env.SAY_VOICE || "Daniel"}" (free)`}`);
  for (const stop of stops) {
    const entry = (content[stop.id] ??= { variants: {} });
    entry.base ??= {};
    let made = 0;
    try {
      made += await ensureAudio(entry.base, stop.story, stop.id, stop.name);
      for (const [tag, v] of Object.entries(entry.variants)) {
        made += await ensureAudio(v, v.story, `${stop.id}--${tag}`, stop.name);
      }
      saveContent(content);
      console.log(`  ${made ? "♪" : "✓"} ${stop.name}${made ? ` (${made} recorded)` : ""}`);
    } catch (err) {
      saveContent(content);
      console.log(`  ✗ ${stop.name}: ${err.message}`);
    }
  }
}

// ---------- review sheet ----------

function writeReview(allStops, content) {
  let md = `# WalkBCN — stories to review\n\nGenerated by Claude. Read each version and check the flagged facts before showing it to users.\n`;
  for (const stop of allStops) {
    const variants = content[stop.id]?.variants ?? {};
    if (!Object.keys(variants).length) continue;
    md += `\n## ${stop.name}\n`;
    for (const [tag, v] of Object.entries(variants)) {
      md += `\n**${tag}**${v.mock ? " _(mock)_" : ""}\n\n${v.story}\n`;
      if (v.facts_to_verify?.length) md += `\nCheck: ${v.facts_to_verify.map((f) => `\n- [ ] ${f}`).join("")}\n`;
    }
  }
  fs.writeFileSync(REVIEW_MD, md);
}

// ---------- main ----------

const allStops = loadAllStops();
const stops = only ? allStops.filter((s) => s.id === only) : allStops;
if (!stops.length) { console.error(`No stop with id "${only}".`); process.exit(1); }
const content = loadContent();

if (doText) {
  if (!MOCK && !process.env.ANTHROPIC_API_KEY) {
    console.error("ANTHROPIC_API_KEY is not set. Run: export ANTHROPIC_API_KEY=sk-ant-...   (or use --audio / --mock)");
    process.exit(1);
  }
  console.log(`Writing stories with ${MOCK ? "MOCK data" : MODEL}:`);
  await generateText(stops, content);
}
if (doAudio) {
  console.log("Recording audio:");
  await generateAudio(stops, content);
}
saveContent(content);
writeReview(allStops, content);
console.log("\nDone. Open content/review.md to check the stories, then reload index.html.");
