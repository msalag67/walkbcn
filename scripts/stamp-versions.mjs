// Ties every data file's version to its content (audit F9, 22 Nov 2026).
//
// Before, index.html asked for data/ui.js?v=19, content/i18n/en.js?v=10… and the numbers were
// raised by hand. The service worker keeps translations "first copy wins", so a forgotten bump
// left phones with old texts for good. Now the version is a short hash of the file itself:
//   - index.html: <script src="data/….js?v=<hash>"> and content/stories.js
//   - data/versions.js: window.WALKBCN_VERSIONS.i18n = { en: "<hash>", ca: …, … }, used by
//     the page to load content/i18n/<lang>.js?v=<hash>
// A file that changes gets a new address, so every browser fetches it once and the service
// worker drops the older copy.
//
// Usage: node scripts/stamp-versions.mjs           update the versions
//        node scripts/stamp-versions.mjs --check   only report (check.mjs uses this)
// import-manual.mjs and translate.mjs run it at the end.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LANGS = ["en", "ca", "es", "fr", "de", "it", "zh"];
const hashOf = (rel) => crypto.createHash("sha1").update(fs.readFileSync(path.join(ROOT, rel))).digest("hex").slice(0, 8);

export function stampVersions({ check = false } = {}) {
  const changed = [];
  const i18n = Object.fromEntries(LANGS.filter((l) => fs.existsSync(path.join(ROOT, `content/i18n/${l}.js`))).map((l) => [l, hashOf(`content/i18n/${l}.js`)]));
  const versionsFile = path.join(ROOT, "data/versions.js");
  const versionsSrc = `// Generated by scripts/stamp-versions.mjs: a short hash of each translation file, so a\n// changed file gets a new address and no browser keeps an old copy. Do not edit by hand.\nwindow.WALKBCN_VERSIONS = ${JSON.stringify({ i18n })};\n`;
  if (!fs.existsSync(versionsFile) || fs.readFileSync(versionsFile, "utf8") !== versionsSrc) {
    changed.push("data/versions.js");
    if (!check) fs.writeFileSync(versionsFile, versionsSrc);
  }
  const htmlFile = path.join(ROOT, "index.html");
  const html = fs.readFileSync(htmlFile, "utf8");
  const out = html.replace(/<script src="((?:data\/[\w-]+|content\/stories)\.js)(?:\?v=[^"]*)?"><\/script>/g, (tag, file) => {
    // in --check mode data/versions.js may not be written yet: hash what it would contain
    const v = file === "data/versions.js" && check ? crypto.createHash("sha1").update(versionsSrc).digest("hex").slice(0, 8) : hashOf(file);
    const next = `<script src="${file}?v=${v}"></script>`;
    if (next !== tag) changed.push(file);
    return next;
  });
  if (out !== html && !check) fs.writeFileSync(htmlFile, out);
  return [...new Set(changed)];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const changed = stampVersions({ check });
  if (check && changed.length) { console.error(`Out of date: ${changed.join(", ")}. Run: node scripts/stamp-versions.mjs`); process.exit(1); }
  console.log(changed.length ? `Updated versions: ${changed.join(", ")}` : "Versions up to date.");
}
