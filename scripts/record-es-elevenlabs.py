#!/usr/bin/env python3
"""Record the Spanish stories with the ElevenLabs voice.

Python twin of `node scripts/translate.mjs --audio --lang=es`, for Macs without Node.
Same voice (RxPoOxDaJiOdJGnMMaql), same model, same file names and same hashes,
so either script can pick up where the other left off.

    python3 scripts/record-es-elevenlabs.py            # records what is missing or out of date
    python3 scripts/record-es-elevenlabs.py --force    # re-records everything
    python3 scripts/record-es-elevenlabs.py --dry-run  # only counts stories and characters
    python3 scripts/record-es-elevenlabs.py --long     # the long (~2 min) versions instead

Standard ("normal") recordings go to entry.audio and audio/es/<id>.mp3, as in translate.mjs.
Long ones go to entry.audioLong and audio/es/long/<id>.mp3. With --long the audio guide's
stories (one per stop, "base") are recorded first, then the routes' interest versions.

The key is read from ELEVENLABS_API_KEY or asked for (hidden) when the script starts.
Progress is saved after every stop; if it stops, run the same command again.
"""
import getpass, hashlib, json, os, re, sys, time, urllib.error, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANG = "es"
VOICE = "RxPoOxDaJiOdJGnMMaql"
MODEL = "eleven_multilingual_v2"
I18N = os.path.join(ROOT, "content", "i18n")
FORCE = "--force" in sys.argv
DRY = "--dry-run" in sys.argv
LONG = "--long" in sys.argv
LENGTH = "long" if LONG else "normal"
FIELD = "audioLong" if LONG else "audio"
SUBDIR = f"audio/{LANG}/long" if LONG else f"audio/{LANG}"


def h(text):
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]


def stops():
    src = open(os.path.join(ROOT, "data", "stops.js"), encoding="utf-8").read()
    out = []
    q = r"(?:'((?:[^'\\]|\\.)*)'|\"((?:[^\"\\]|\\.)*)\")"
    for m in re.finditer(r"\{\s*id:\s*" + q + r",\s*name:\s*" + q, src):
        sid = m.group(1) if m.group(1) is not None else m.group(2)
        name = m.group(3) if m.group(3) is not None else m.group(4)
        out.append((sid, re.sub(r"\\(.)", r"\1", name)))
    return out


def save(data):
    with open(os.path.join(I18N, f"{LANG}.json"), "w", encoding="utf-8") as f:
        f.write(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    with open(os.path.join(I18N, f"{LANG}.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/translate.mjs and scripts/import-manual.mjs — do not edit by hand.\n"
                "window.WALKBCN_I18N = window.WALKBCN_I18N || {};\n"
                f"window.WALKBCN_I18N[{json.dumps(LANG)}] = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n")


def stamp_versions():
    """Same as scripts/stamp-versions.mjs: tie each file's ?v= to its content."""
    hof = lambda rel: hashlib.sha1(open(os.path.join(ROOT, rel), "rb").read()).hexdigest()[:8]
    langs = [l for l in ["en", "ca", "es", "fr", "de", "it", "zh"] if os.path.exists(os.path.join(I18N, f"{l}.js"))]
    src = ("// Generated by scripts/stamp-versions.mjs: a short hash of each translation file, so a\n"
           "// changed file gets a new address and no browser keeps an old copy. Do not edit by hand.\n"
           f"window.WALKBCN_VERSIONS = {json.dumps({'i18n': {l: hof(f'content/i18n/{l}.js') for l in langs}}, separators=(',', ':'))};\n")
    with open(os.path.join(ROOT, "data", "versions.js"), "w", encoding="utf-8") as f:
        f.write(src)
    html_file = os.path.join(ROOT, "index.html")
    html = open(html_file, encoding="utf-8").read()
    out = re.sub(r'<script src="((?:data/[\w-]+|content/stories)\.js)(?:\?v=[^"]*)?"></script>',
                 lambda m: f'<script src="{m.group(1)}?v={hof(m.group(1))}"></script>', html)
    if out != html:
        with open(html_file, "w", encoding="utf-8") as f:
            f.write(out)


def record(key, text, out_file):
    url = f"https://api.elevenlabs.io/v1/text-to-speech/{VOICE}?output_format=mp3_44100_64"
    body = json.dumps({"text": text, "model_id": MODEL}).encode("utf-8")
    for attempt in range(1, 4):
        req = urllib.request.Request(url, data=body, method="POST", headers={
            "xi-api-key": key, "Content-Type": "application/json", "Accept": "audio/mpeg"})
        try:
            with urllib.request.urlopen(req, timeout=180) as r:
                audio = r.read()
            with open(out_file, "wb") as f:
                f.write(audio)
            return
        except urllib.error.HTTPError as e:
            msg = e.read().decode("utf-8", "replace")[:300]
            if (e.code < 500 and e.code != 429) or attempt == 3:
                raise RuntimeError(f"ElevenLabs {e.code}: {msg}")
        except urllib.error.URLError as e:
            if attempt == 3:
                raise RuntimeError(f"network: {e.reason}")
        time.sleep(5 * attempt)


def main():
    data = json.load(open(os.path.join(I18N, f"{LANG}.json"), encoding="utf-8"))
    todo = []
    for sid, name in stops():
        entry = data["stops"].get(sid)
        if not entry:
            continue
        for k, v in entry["stories"].items():
            if not v.get(LENGTH):
                continue
            spoken = f"{name}. {v[LENGTH]}"
            rel = f"{SUBDIR}/{sid if k == 'base' else f'{sid}--{k}'}.mp3"
            hh = h(f"{VOICE}|{spoken}")
            prev = (entry.get(FIELD) or {}).get(k)
            if not FORCE and prev and prev.get("file") == rel and prev.get("hash") == hh and os.path.exists(os.path.join(ROOT, rel)):
                continue
            todo.append((sid, name, k, spoken, rel, hh))

    todo.sort(key=lambda t: t[2] != "base")  # one per stop first: that is what the audio guide plays
    chars = sum(len(t[3]) for t in todo)
    print(f"Spanish {LENGTH}, ElevenLabs voice {VOICE}: {len(todo)} stories to record, {chars:,} characters.")
    if LONG:
        guide = [t for t in todo if t[2] == "base"]
        print(f"  first the audio guide: {len(guide)} stories, {sum(len(t[3]) for t in guide):,} characters")
    if DRY or not todo:
        return
    key = os.environ.get("ELEVENLABS_API_KEY") or getpass.getpass("ElevenLabs API key (hidden): ").strip()
    if not key:
        sys.exit("No key, nothing recorded.")

    done = 0
    for sid, name, k, spoken, rel, hh in todo:
        entry = data["stops"][sid]
        try:
            os.makedirs(os.path.dirname(os.path.join(ROOT, rel)), exist_ok=True)
            record(key, spoken, os.path.join(ROOT, rel))
        except RuntimeError as e:
            save(data)
            stamp_versions()
            sys.exit(f"\nStopped at {name} ({k}): {e}\n{done} recorded and saved. Run the same command again to continue.")
        prev = (entry.get(FIELD) or {}).get(k)
        if prev and prev.get("file") and prev["file"] != rel:
            try:
                os.remove(os.path.join(ROOT, prev["file"]))
            except FileNotFoundError:
                pass
        entry.setdefault(FIELD, {})[k] = {"file": rel, "hash": hh}
        done += 1
        save(data)
        print(f"  [{done}/{len(todo)}] {name} ({k})")
    stamp_versions()
    print(f"Done: {done} Spanish {LENGTH} stories recorded.")


if __name__ == "__main__":
    main()
