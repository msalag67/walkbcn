// WalkBCN languages and story lengths.
//
// 1. Lengths:   asks Claude for a short (~30 s) and a long (~2 min) English version of
//               every story, next to the existing normal one (~1 min).
// 2. Languages: translates every story (3 lengths), tip and the Activities texts into
//               Catalan, Spanish, French, German, Italian and Chinese.
// 3. Audio:     records the normal-length story in each language with the macOS voice
//               for that language. Short and long versions are read by the phone's voice.
//
// Everything is saved in content/i18n/<lang>.json (+ .js for the page). Only missing
// pieces are generated, so the script can be stopped and run again.
//
// Usage:
//   node scripts/translate.mjs                 everything that is missing
//   node scripts/translate.mjs --lengths       only the English short/long versions
//   node scripts/translate.mjs --lang=fr       only one language (text + audio)
//   node scripts/translate.mjs --audio         only record audio
//   node scripts/translate.mjs --only=casa-batllo
//   node scripts/translate.mjs --force         redo the selected parts
//
// Needs ANTHROPIC_API_KEY for text (not for --audio).
// Spanish audio uses the ElevenLabs voice RxPoOxDaJiOdJGnMMaql when ELEVENLABS_API_KEY is set
// (saved as .mp3). Re-record it with:  node scripts/translate.mjs --audio --lang=es

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import Anthropic from "@anthropic-ai/sdk";
import { MODEL } from "./story-writer.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const I18N_DIR = path.join(ROOT, "content/i18n");
const LANGS = {
  ca: { name: "Catalan", voices: ["Montse"], locale: "ca_ES" },
  // Spanish uses a natural ElevenLabs voice (needs ELEVENLABS_API_KEY); macOS Mónica is the fallback.
  es: { name: "Spanish (Spain)", voices: ["Mónica", "Monica"], locale: "es_ES", elevenVoice: "RxPoOxDaJiOdJGnMMaql" },
  fr: { name: "French", voices: ["Thomas", "Jacques", "Amélie"], locale: "fr_FR" },
  de: { name: "German", voices: ["Anna", "Helena"], locale: "de_DE" },
  it: { name: "Italian", voices: ["Alice", "Federica"], locale: "it_IT" },
  zh: { name: "Simplified Chinese (Mandarin)", voices: ["Tingting", "Ting-Ting", "Lili"], locale: "zh_CN" },
};

const args = process.argv.slice(2);
const flag = (n) => args.includes(`--${n}`);
const opt = (n) => args.find((a) => a.startsWith(`--${n}=`))?.split("=")[1];
const ONLY = opt("only");
const LANG_ONLY = opt("lang");
const FORCE = flag("force");
const doLengths = flag("lengths") || (!flag("audio") && !LANG_ONLY);
const doText = !flag("lengths") && !flag("audio");
const doAudio = flag("audio") || (!flag("lengths"));
const langs = LANG_ONLY ? [LANG_ONLY] : Object.keys(LANGS);
if (LANG_ONLY && !LANGS[LANG_ONLY]) { console.error(`Unknown language "${LANG_ONLY}". Use one of: ${Object.keys(LANGS).join(", ")}`); process.exit(1); }

// ---------- data ----------
function loadWindowVar(file, name) {
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, file), "utf8"), ctx);
  return ctx.window[name];
}
const STOPS = loadWindowVar("data/stops.js", "WALKBCN_STOPS").filter((s) => !ONLY || s.id === ONLY);
const ACTIVITIES = loadWindowVar("data/activities.js", "WALKBCN_ACTIVITIES");
const STORIES = JSON.parse(fs.readFileSync(path.join(ROOT, "content/stories.json"), "utf8"));

const load = (lang) => {
  const f = path.join(I18N_DIR, `${lang}.json`);
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : { stops: {}, activities: null };
};
function save(lang, data) {
  fs.mkdirSync(I18N_DIR, { recursive: true });
  fs.writeFileSync(path.join(I18N_DIR, `${lang}.json`), JSON.stringify(data, null, 2) + "\n");
  // A plain <script> works even when index.html is opened straight from disk.
  fs.writeFileSync(path.join(I18N_DIR, `${lang}.js`),
    `// Generated by scripts/translate.mjs — do not edit by hand.\nwindow.WALKBCN_I18N = window.WALKBCN_I18N || {};\nwindow.WALKBCN_I18N[${JSON.stringify(lang)}] = ${JSON.stringify(data)};\n`);
}
const hash = (t) => crypto.createHash("sha1").update(t).digest("hex").slice(0, 10);

// The English story set for a stop: the base story plus one version per interest.
function englishNormal(stop) {
  const out = { base: stop.story };
  for (const [tag, v] of Object.entries(STORIES[stop.id]?.variants ?? {})) out[tag] = v.story;
  return out;
}

// Runs fn over items with at most `limit` at a time.
async function pool(items, limit, fn) {
  let i = 0;
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (i < items.length) await fn(items[i++]);
  }));
}

// ---------- Claude ----------
// Errors that no retry will fix (no credit, bad key): stop the whole run straight away.
let fatal = null;
function isFatal(err) {
  return err?.status === 401 || err?.status === 403 || /credit balance|billing/i.test(err?.message || "");
}
let client;
async function ask(system, user, effort) {
  if (fatal) throw fatal;
  // Many requests run at once, so allow more automatic retries if we hit rate limits.
  client ??= new Anthropic({ maxRetries: 8 });
  const response = await client.beta.messages.create({
    model: MODEL,
    max_tokens: 16000,
    output_config: { effort },
    // If a request is ever declined by a safety classifier, the API retries it on
    // a suitable fallback model instead of failing.
    betas: ["server-side-fallback-2026-07-01"],
    fallbacks: "default",
    system,
    messages: [{ role: "user", content: user }],
  }).catch((err) => {
    if (isFatal(err)) fatal ??= err;
    throw err;
  });
  if (response.stop_reason === "refusal") throw new Error(`declined (${response.stop_details?.category ?? "no category"})`);
  if (response.stop_reason === "max_tokens") throw new Error("response was cut off");
  const text = response.content.filter((b) => b.type === "text").map((b) => b.text).join("");
  return JSON.parse(text.slice(text.indexOf("{"), text.lastIndexOf("}") + 1));
}

const LENGTHS_SYSTEM = `You adapt short audio stories for WalkBCN, a walking-tour guide for tourists in central Barcelona.
For each story you get the normal version (about 1 minute when heard). Write two more versions of it:
- "short": 40 to 55 words (about 30 seconds). Keep the single most vivid detail and one thing to look at.
- "long": 220 to 280 words (about 2 minutes). Go deeper, with more to notice from where the listener stands.
Rules: plain spoken English, speak to the listener, no lists or headings. Keep the facts of the normal version. In the long version you may add only well-established facts; never invent dates, numbers, quotes or legends, and list every new specific fact you add in "new_facts". Keep WalkBCN's respect for residents.
Reply with JSON only: {"stories":{"<key>":{"short":"...","long":"...","new_facts":["..."]}}}`;

const TRANSLATE_SYSTEM = (lang) => `You translate audio stories and short texts for WalkBCN, a walking-tour guide for tourists in central Barcelona, into ${LANGS[lang].name}.
- Natural, warm, spoken ${LANGS[lang].name}, as a good local guide would say it out loud. Not word for word.
- Keep every fact exactly; add nothing, remove nothing.
- Keep place names in their local Catalan form (e.g. Plaça del Rei, Casa Batlló, Sagrada Família)${lang === "zh" ? ", and add a common Chinese name in brackets the first time when one exists" : ""}.
- Keep the same JSON structure and keys; translate only the string values.
Reply with JSON only.`;

// ---------- 1. English short and long versions ----------
async function makeLengths(en) {
  console.log("English short and long versions:");
  await pool(STOPS, 6, async (stop) => {
    const normal = englishNormal(stop);
    const entry = (en.stops[stop.id] ??= { stories: {}, tip: stop.tip });
    entry.tip = stop.tip;
    const todo = Object.keys(normal).filter((k) => FORCE || !entry.stories[k]?.short || !entry.stories[k]?.long || entry.stories[k].normal !== normal[k]);
    if (!todo.length) { console.log(`  ✓ ${stop.name}`); return; }
    try {
      const json = await ask(LENGTHS_SYSTEM,
        `Stop: ${stop.name} (${stop.area}, Barcelona)\nNormal versions:\n` + JSON.stringify(Object.fromEntries(todo.map((k) => [k, normal[k]])), null, 2),
        "medium");
      for (const k of todo) {
        const v = json.stories?.[k];
        if (!v?.short || !v?.long) throw new Error(`missing version for "${k}"`);
        entry.stories[k] = { short: v.short.trim(), normal: normal[k], long: v.long.trim(), new_facts: v.new_facts ?? [] };
      }
      save("en", en);
      console.log(`  ✓ ${stop.name} → ${todo.length} stories`);
    } catch (err) {
      console.log(`  ✗ ${stop.name}: ${err.message}`);
    }
  });
}

// ---------- 2. translations ----------
async function translateStops(lang, en, data) {
  await pool(STOPS, 3, async (stop) => {
    const source = en.stops[stop.id];
    if (!source) { console.log(`  [${lang}] – ${stop.name}: no English versions yet`); return; }
    const srcHash = hash(JSON.stringify([source.stories, source.tip]));
    const entry = data.stops[stop.id];
    if (!FORCE && entry?.srcHash === srcHash) return;
    try {
      const payload = { tip: source.tip, stories: Object.fromEntries(Object.entries(source.stories).map(([k, v]) => [k, { short: v.short, normal: v.normal, long: v.long }])) };
      const json = await ask(TRANSLATE_SYSTEM(lang), `Stop: ${stop.name}\nTranslate:\n` + JSON.stringify(payload, null, 2), "low");
      for (const k of Object.keys(payload.stories)) {
        const v = json.stories?.[k];
        if (!v?.short || !v?.normal || !v?.long) throw new Error(`missing translation for "${k}"`);
      }
      if (!json.tip) throw new Error("missing tip");
      data.stops[stop.id] = { tip: json.tip, stories: json.stories, srcHash, audio: entry?.audio ?? {} };
      save(lang, data);
      console.log(`  [${lang}] ✓ ${stop.name}`);
    } catch (err) {
      console.log(`  [${lang}] ✗ ${stop.name}: ${err.message}`);
    }
  });
}

function activitiesSource() {
  const out = {};
  for (const [id, cat] of Object.entries(ACTIVITIES)) {
    out[id] = {
      label: cat.label, intro: cat.intro,
      filters: Object.fromEntries(cat.filters.map((f) => [f.id, { label: f.label, options: Object.fromEntries(f.options.map((o) => [o.id, o.label])) }])),
      places: Object.fromEntries(cat.places.map((p) => [p.name, p.desc])),
    };
  }
  return out;
}
async function translateActivities(lang, data) {
  const source = activitiesSource();
  const srcHash = hash(JSON.stringify(source));
  if (!FORCE && data.activitiesHash === srcHash) return;
  try {
    const json = await ask(TRANSLATE_SYSTEM(lang),
      "Translate these Activities texts. Keep the place names (the keys under \"places\") unchanged; translate their descriptions. Keep \"€\" labels as they are.\n" + JSON.stringify(source, null, 2), "low");
    for (const id of Object.keys(source)) if (!json[id]?.label) throw new Error(`missing category "${id}"`);
    data.activities = json;
    data.activitiesHash = srcHash;
    save(lang, data);
    console.log(`  [${lang}] ✓ Activities`);
  } catch (err) {
    console.log(`  [${lang}] ✗ Activities: ${err.message}`);
  }
}

// ---------- 3. audio (normal length, macOS voices) ----------
let voiceList;
function pickVoice(lang) {
  voiceList ??= execFileSync("say", ["-v", "?"], { encoding: "utf8" }).split("\n")
    .map((l) => l.match(/^(.+?)\s{2,}([a-z]{2}_[A-Z]{2})/)).filter(Boolean).map((m) => ({ name: m[1].trim(), locale: m[2] }));
  const { voices, locale } = LANGS[lang];
  const inLocale = voiceList.filter((v) => v.locale === locale);
  return (voices.map((n) => inLocale.find((v) => v.name === n)).find(Boolean) || inLocale.find((v) => !/\(/.test(v.name)) || inLocale[0])?.name;
}
function record(text, voice, outFile) {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  const tmpTxt = `${outFile}.txt`, tmpAiff = `${outFile}.aiff`;
  fs.writeFileSync(tmpTxt, text);
  try {
    execFileSync("say", ["-v", voice, "-f", tmpTxt, "-o", tmpAiff]);
    // 32 kbps mono AAC: clear for speech and half the size of the English files.
    execFileSync("afconvert", ["-f", "m4af", "-d", "aac", "-c", "1", "-b", "32000", tmpAiff, outFile]);
  } finally {
    fs.rmSync(tmpTxt, { force: true });
    fs.rmSync(tmpAiff, { force: true });
  }
}
const ELEVEN_KEY = process.env.ELEVENLABS_API_KEY;
async function recordEleven(text, voiceId, outFile) {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voiceId}?output_format=mp3_44100_64`, {
        method: "POST",
        headers: { "xi-api-key": ELEVEN_KEY, "Content-Type": "application/json", Accept: "audio/mpeg" },
        body: JSON.stringify({ text, model_id: "eleven_multilingual_v2" }),
        signal: AbortSignal.timeout(90_000), // never hang forever on a stuck request
      });
      if (!res.ok) throw Object.assign(new Error(`ElevenLabs ${res.status}: ${await res.text()}`), { fatal: res.status < 500 && res.status !== 429 });
      fs.writeFileSync(outFile, Buffer.from(await res.arrayBuffer()));
      return;
    } catch (err) {
      if (err.fatal || attempt >= 3) throw err; // bad key / no credit: stop; network blips: retry
      await new Promise((r) => setTimeout(r, 5000 * attempt));
    }
  }
}
async function recordAudio(lang, data) {
  const elevenVoice = LANGS[lang].elevenVoice;
  if (elevenVoice && !ELEVEN_KEY) console.log(`  ! ELEVENLABS_API_KEY is not set: ${LANGS[lang].name} falls back to the macOS voice`);
  const useEleven = Boolean(elevenVoice && ELEVEN_KEY);
  const voice = useEleven ? `ElevenLabs ${elevenVoice}` : pickVoice(lang);
  if (!voice) { console.log(`  ✗ no macOS voice installed for ${LANGS[lang].name}`); return; }
  const ext = useEleven ? "mp3" : "m4a";
  console.log(`Recording ${LANGS[lang].name} (voice: ${voice})…`);
  for (const stop of STOPS) {
    const entry = data.stops[stop.id];
    if (!entry) continue;
    entry.audio ??= {};
    let made = 0;
    for (const [k, v] of Object.entries(entry.stories)) {
      const spoken = `${stop.name}. ${v.normal}`;
      const rel = `audio/${lang}/${k === "base" ? stop.id : `${stop.id}--${k}`}.${ext}`;
      const prev = entry.audio[k];
      const h = useEleven ? hash(`${elevenVoice}|${spoken}`) : hash(spoken); // a new ElevenLabs voice re-records
      if (!FORCE && prev?.file === rel && prev.hash === h && fs.existsSync(path.join(ROOT, rel))) continue;
      // Without the ElevenLabs key, keep a natural-voice recording whose text hasn't changed
      // (its hash includes the voice), instead of replacing it with the macOS voice.
      if (!FORCE && !useEleven && elevenVoice && prev?.file?.endsWith(".mp3") && prev.hash === hash(`${elevenVoice}|${spoken}`) && fs.existsSync(path.join(ROOT, prev.file))) continue;
      try {
        if (useEleven) await recordEleven(spoken, elevenVoice, path.join(ROOT, rel));
        else record(spoken, voice, path.join(ROOT, rel));
      } catch (err) {
        console.log(`  [${lang}] ✗ ${stop.name} (${k}): ${err.message}`);
        save(lang, data);
        return; // stop this language; run the same command again to continue
      }
      if (prev?.file && prev.file !== rel) fs.rmSync(path.join(ROOT, prev.file), { force: true });
      entry.audio[k] = { file: rel, hash: h };
      made++;
    }
    save(lang, data);
    if (made) console.log(`  [${lang}] ♪ ${stop.name} (${made} recorded)`);
  }
}

// ---------- main ----------
const needsKey = doLengths || doText;
if (needsKey && !process.env.ANTHROPIC_API_KEY) {
  console.error("ANTHROPIC_API_KEY is not set. Run: export ANTHROPIC_API_KEY=sk-ant-...   (or use --audio)");
  process.exit(1);
}
const en = load("en");
if (doLengths) await makeLengths(en);
const stopIfFatal = () => {
  if (!fatal) return;
  console.error(`\nStopped: ${/credit balance/i.test(fatal.message) ? "your API credit has run out. Add credit in Claude Console (Billing), then run the same command again" : fatal.message}.`);
  console.error("Everything generated so far is saved.");
  process.exit(1);
};
stopIfFatal();
const targets = langs.filter((l) => l !== "en").map((lang) => ({ lang, data: load(lang) }));
if (doText) {
  console.log(`Translating into ${targets.map((t) => LANGS[t.lang].name).join(", ")} (all at once)…`);
  await Promise.all(targets.map(async ({ lang, data }) => {
    await translateStops(lang, en, data);
    await translateActivities(lang, data);
  }));
}
stopIfFatal();
if (doAudio) for (const { lang, data } of targets) await recordAudio(lang, data);
const missing = targets.flatMap(({ lang, data }) => STOPS.filter((s) => !data.stops[s.id]).map((s) => `${lang}/${s.id}`));
if (missing.length) console.log(`\nStill missing (run the same command again): ${missing.join(", ")}`);
console.log("\nDone. Reload the web page to see the new languages.");
